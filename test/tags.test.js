const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const tags = require('../tags');
const trash = require('../gallery-trash');

test('shared tags are reusable and follow renamed, trashed and restored galleries', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'imageworks-tags-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const gallery = path.join(root, 'Gallery'), bin = path.join(root, 'Trash');
  await fs.mkdir(path.join(gallery, 'One'), { recursive: true });
  await fs.mkdir(path.join(gallery, 'Two'));
  const portrait = await tags.createTag(root, '  Portraits  ');
  const favourite = await tags.createTag(root, 'Favourites');
  await tags.colourTag(root, portrait.id, 'blue');
  assert.equal((await tags.library(root)).find(tag => tag.id === portrait.id).colour, 'blue');
  await assert.rejects(tags.colourTag(root, portrait.id, 'not-a-colour'), /Invalid/);
  await assert.rejects(tags.createTag(root, 'portraits'), /already exists/);
  await tags.assignTags(root, gallery, 'One', [portrait.id, favourite.id, portrait.id]);
  await tags.assignTags(root, gallery, 'Two', [portrait.id]);
  assert.deepEqual(await tags.galleryTags(path.join(gallery, 'One')), [portrait.id, favourite.id]);
  await fs.rename(path.join(gallery, 'One'), path.join(gallery, 'Renamed'));
  const moved = await trash.moveToTrash(gallery, bin, 'Renamed');
  await tags.changeTag(root, portrait.id, 'People');
  await tags.changeTag(root, favourite.id, null);
  await trash.restoreTrash(gallery, bin, moved.id);
  const library = await tags.library(root);
  const restored = await tags.galleryTags(path.join(gallery, 'Renamed'));
  assert.deepEqual(library.filter(tag => restored.includes(tag.id)).map(tag => tag.name), ['People']);
  assert.deepEqual(await tags.galleryTags(path.join(gallery, 'Two')), [portrait.id]);
  await assert.rejects(tags.assignTags(root, gallery, '../outside', [portrait.id]), /Invalid gallery/);
  await assert.rejects(tags.assignTags(root, gallery, 'Two', [favourite.id]), /no longer exists/);
  assert.deepEqual(await tags.galleryTags(path.join(gallery, 'Two')), [portrait.id]);
  await fs.writeFile(path.join(gallery, 'Two', tags.TAG_FILE), '{broken');
  await assert.rejects(tags.assignTags(root, gallery, 'Two', []));
  assert.equal(await fs.readFile(path.join(gallery, 'Two', tags.TAG_FILE), 'utf8'), '{broken');
});
